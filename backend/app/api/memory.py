from fastapi import APIRouter, Depends
from pydantic import BaseModel

from app.deps import get_store
from app.memory.hindsight_store import MemoryStore
from app.models.schemas import Evidence

router = APIRouter(prefix="/api", tags=["memory"])


class ReflectRequest(BaseModel):
    query: str | None = None


class ReflectResponse(BaseModel):
    text: str


@router.get("/memory/status")
def memory_status(store: MemoryStore = Depends(get_store)) -> dict:
    return store.status()


@router.get("/memory/search", response_model=list[Evidence])
def search_memory(q: str, store: MemoryStore = Depends(get_store)):
    return store.search(q)


@router.post("/reflect", response_model=ReflectResponse)
def reflect(req: ReflectRequest | None = None, store: MemoryStore = Depends(get_store)):
    """Pipeline Health Brief generated by Hindsight reflect."""
    return ReflectResponse(text=store.reflect(req.query if req else None))
